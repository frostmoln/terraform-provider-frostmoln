func (r *userResource) Configure(_ context.Context, req resource.ConfigureRequest, resp *resource.ConfigureResponse) {
	if req.ProviderData == nil {
		return
	}
	c, ok := req.ProviderData.(*client.Client)
	if !ok {
		resp.Diagnostics.AddError(
			"Unexpected Resource Configure Type",
			fmt.Sprintf("Expected *client.Client, got: %T", req.ProviderData),
		)
		return
	}
	r.client = c
}

func subject(instanceID, name string) string {
	return fmt.Sprintf("User %q on messaging instance %s", name, instanceID)
}

func (r *userResource) get(ctx context.Context, instanceID, name string) (*messagingobj.Object, error) {
	apiResp, err := r.client.Get(ctx, messagingobj.UserPath(r.client, instanceID, name), nil)
	if err != nil {
		return nil, err
	}
	u, err := client.ParseResponse[messagingobj.Object](apiResp)
	if err != nil {
		return nil, err
	}
	if !sameName(name, u.Name) {
		return nil, messagingobj.Mismatch("requested user %q but the API answered with %q", name, u.Name)
	}
	return u, nil
}

func (r *userResource) wait(ctx context.Context, instanceID, name string, budget time.Duration) (*messagingobj.Object, bool, error) {
	return messagingobj.Wait(ctx, r.pollInterval, budget, "messaging user",
		func(ctx context.Context) (*messagingobj.Object, error) { return r.get(ctx, instanceID, name) },
		func(u *messagingobj.Object) string { return u.Status })
}

// readPassword fetches the user's password. It is served only once the user is
// `ready` (409 OBJECT_NOT_READY before), with Cache-Control: no-store. The
// value is never logged or put in a diagnostic.
func (r *userResource) readPassword(ctx context.Context, instanceID, name string) (string, error) {
	apiResp, err := r.client.Get(ctx, messagingobj.CredentialsPath(r.client, instanceID, name), nil)
	if err != nil {
		return "", err
	}
	creds, err := client.ParseResponse[messagingobj.Credentials](apiResp)
	if err != nil {
		return "", fmt.Errorf("the credentials response could not be read")
	}
	if creds.Password == "" {
		return "", fmt.Errorf("the credentials response carried no password")
	}
	return creds.Password, nil
}

// readPasswordUntil retries the password read while the platform answers
// OBJECT_NOT_READY (the user's verdict can land a moment before its
// credentials are served) or a 5xx, until deadline. A zero deadline is one try.
func (r *userResource) readPasswordUntil(ctx context.Context, instanceID, name string, deadline time.Time) (string, error) {
	interval := r.pollInterval
	if interval <= 0 {
		interval = messagingobj.DefaultPollInterval
	}
	for {
		pw, err := r.readPassword(ctx, instanceID, name)
		if err == nil || !retryableCredentialsError(err) || time.Now().Add(interval).After(deadline) {
			return pw, err
		}
		select {
		case <-ctx.Done():
			return "", ctx.Err()
		case <-time.After(interval):
		}
	}
}

func retryableCredentialsError(err error) bool {
	if messagingobj.HasCode(err, messagingobj.CodeObjectNotReady) {
		return true
	}
	var apiErr *client.APIError
	return errors.As(err, &apiErr) && apiErr.StatusCode >= 500
}

// refreshPassword records the password of a ready user, keeping the one in the
// model when it cannot be read (a warning, never an error: the user itself is
// fine, and a refresh retries). deadline bounds retries (zero: one try).
func (r *userResource) refreshPassword(ctx context.Context, m *userModel, diags *diag.Diagnostics, deadline time.Time) {
	if m.Status.ValueString() != messagingobj.StatusReady {
		if m.Password.IsUnknown() {
			m.Password = types.StringNull()
		}
		return
	}
	pw, err := r.readPasswordUntil(ctx, m.InstanceID.ValueString(), m.Name.ValueString(), deadline)
	if err != nil {
		if m.Password.IsUnknown() {
			m.Password = types.StringNull()
		}
		diags.AddWarning("The messaging user's password could not be read",
			subject(m.InstanceID.ValueString(), m.Name.ValueString())+" is ready, but its password could not be "+
				"read: "+err.Error()+". The next refresh reads it.")
		return
	}
	m.Password = types.StringValue(pw)
}

func (r *userResource) Create(ctx context.Context, req resource.CreateRequest, resp *resource.CreateResponse) {
	ctx = messagingobj.English(ctx)
	var plan userModel
	resp.Diagnostics.Append(req.Plan.Get(ctx, &plan)...)
	if resp.Diagnostics.HasError() {
		return
	}
	instanceID, name := plan.InstanceID.ValueString(), plan.Name.ValueString()
	subj := subject(instanceID, name)

	release, err := messagingobj.Lock(ctx, instanceID)
	if err != nil {
		messagingobj.AddLockError(&resp.Diagnostics, err)
		return
	}
	defer release()

	budget := messagingobj.Budgets(plan.Timeouts).Create
	deadline := time.Now().Add(budget)
	apiResp, err := r.client.Post(ctx, messagingobj.UsersPath(r.client, instanceID), messagingobj.CreateRequest{Name: name})
	if err != nil {
		messagingobj.AddRefusal(&resp.Diagnostics, "Failed to create the messaging user", subj, err)
		return
	}
	// The 202 body is the staged user (never with a password): the fallback
	// record if no poll lands.
	staged, _ := client.ParseResponse[messagingobj.Object](apiResp)

	u, gone, waitErr := r.wait(ctx, instanceID, name, budget)
	if u == nil {
		u = staged
	}
	plan.Password = types.StringNull()
	switch {
	case gone:
		resp.Diagnostics.AddError("The messaging user disappeared while it was being created",
			subj+" was deleted before its create finished — most likely by another client. Nothing was recorded; "+
				"apply again to create it.")
		return
	case waitErr != nil:
		if u != nil {
			plan.fromAPI(u)
			resp.Diagnostics.Append(resp.State.Set(ctx, &plan)...)
		}
		resp.Diagnostics.AddError("The messaging user did not finish creating",
			fmt.Sprintf("%s: %s. It is recorded with its last known status and marked tainted, so the next apply "+
				"deletes and re-creates it; if a refresh shows it `ready`, `terraform untaint` keeps it instead.",
				subj, waitErr.Error()))
		return
	}

	plan.fromAPI(u)
	outcome := messagingobj.Judge(u.Status, u.FailureReason)
	if outcome == messagingobj.Succeeded {
		r.refreshPassword(ctx, &plan, &resp.Diagnostics, deadline)
	}
	resp.Diagnostics.Append(resp.State.Set(ctx, &plan)...)
	switch outcome {
	case messagingobj.Errored:
		resp.Diagnostics.AddError("Failed to create the messaging user",
			fmt.Sprintf("%s could not be created: %s. %s It is recorded as tainted, so the next apply deletes the "+
				"failed user (locally, when it never reached the broker) and creates it again.",
				subj, messagingobj.FailureText(u.FailureReason, u.FailureMessage), messagingobj.BrokerSentence(u.FailureReason)))
	case messagingobj.ChangeFailed:
		resp.Diagnostics.AddError("Failed to create the messaging user",
			fmt.Sprintf("%s reads `ready` but its last change failed: %s. %s",
				subj, messagingobj.FailureText(u.FailureReason, u.FailureMessage), messagingobj.BrokerSentence(u.FailureReason)))
	}
}

// Read refreshes the user and, when it is ready, its password — which is how an
// import, or a create whose password read failed, gets one.
func (r *userResource) Read(ctx context.Context, req resource.ReadRequest, resp *resource.ReadResponse) {
	ctx = messagingobj.English(ctx)
	var state userModel
	resp.Diagnostics.Append(req.State.Get(ctx, &state)...)
	if resp.Diagnostics.HasError() {
		return
	}
	u, err := r.get(ctx, state.InstanceID.ValueString(), state.Name.ValueString())
	if err != nil {
		if client.IsNotFound(err) {
			resp.State.RemoveResource(ctx)
			return
		}
		resp.Diagnostics.AddError("Failed to read the messaging user", err.Error())
		return
	}
	state.fromAPI(u)
	messagingobj.WarnIfErrored(&resp.Diagnostics, subject(state.InstanceID.ValueString(), state.Name.ValueString()),
		u.Status, u.FailureReason, u.FailureMessage)
	r.refreshPassword(ctx, &state, &resp.Diagnostics, time.Time{})
	resp.Diagnostics.Append(resp.State.Set(ctx, &state)...)
}

// Update is reached only by a change to the timeouts block: every
// configurable attribute replaces. Nothing is sent; the user is re-read.
func (r *userResource) Update(ctx context.Context, req resource.UpdateRequest, resp *resource.UpdateResponse) {
	ctx = messagingobj.English(ctx)
	var plan, state userModel
	resp.Diagnostics.Append(req.Plan.Get(ctx, &plan)...)
	resp.Diagnostics.Append(req.State.Get(ctx, &state)...)
	if resp.Diagnostics.HasError() {
		return
	}
	plan.ID = types.StringValue(plan.InstanceID.ValueString() + "/" + plan.Name.ValueString())
	plan.Status, plan.FailureReason = state.Status, state.FailureReason
	plan.FailureMessage, plan.CreatedAt, plan.UpdatedAt = state.FailureMessage, state.CreatedAt, state.UpdatedAt
	plan.Password = state.Password // pragma: allowlist secret
	if u, err := r.get(ctx, plan.InstanceID.ValueString(), plan.Name.ValueString()); err == nil {
		plan.fromAPI(u)
	}
	resp.Diagnostics.Append(resp.State.Set(ctx, &plan)...)
}

func (r *userResource) Delete(ctx context.Context, req resource.DeleteRequest, resp *resource.DeleteResponse) {
	ctx = messagingobj.English(ctx)
	var state userModel
	resp.Diagnostics.Append(req.State.Get(ctx, &state)...)
	if resp.Diagnostics.HasError() {
		return
	}
	instanceID, name := state.InstanceID.ValueString(), state.Name.ValueString()
	subj := subject(instanceID, name)

	release, err := messagingobj.Lock(ctx, instanceID)
	if err != nil {
		messagingobj.AddLockError(&resp.Diagnostics, err)
		return
	}
	defer release()

	apiResp, err := r.client.Delete(ctx, messagingobj.UserPath(r.client, instanceID, name))
	if err != nil {
		switch {
		case client.IsNotFound(err):
			return
		case messagingobj.HasCode(err, messagingobj.CodeObjectInUse):
			resp.Diagnostics.AddError("The messaging user is still in use",
				messagingobj.InUseDetail(ctx, r.client, messagingobj.UserPermissionsPath(r.client, instanceID, name),
					subj, "vhosts", func(p messagingobj.Permission) string { return p.Vhost })+"\n\nError: "+err.Error())
		default:
			messagingobj.AddRefusal(&resp.Diagnostics, "Failed to delete the messaging user", subj, err)
		}
		return
	}
	if apiResp.StatusCode == http.StatusNoContent {
		return
	}

	u, gone, waitErr := r.wait(ctx, instanceID, name, messagingobj.Budgets(state.Timeouts).Delete)
	if gone {
		return
	}
	if waitErr != nil {
		resp.Diagnostics.AddError("The messaging user did not finish deleting",
			fmt.Sprintf("%s: %s. It stays in state; apply again to finish the destroy.", subj, waitErr.Error()))
		return
	}
	resp.Diagnostics.AddError("The messaging user was NOT deleted",
		fmt.Sprintf("%s reads `%s` after its delete: %s. %s Its password still works. It stays in state; apply "+
			"again to retry.",
			subj, u.Status, messagingobj.FailureText(u.FailureReason, u.FailureMessage), messagingobj.BrokerSentence(u.FailureReason)))
}

// ImportState takes "<instance_id>/<name>". The Read that follows fetches the
// password.
func (r *userResource) ImportState(ctx context.Context, req resource.ImportStateRequest, resp *resource.ImportStateResponse) {
	parts, err := client.ParseImportID(req.ID, "instance_id", "name")
	if err != nil {
		resp.Diagnostics.AddError("Invalid Import ID", err.Error())
		return
	}
	resp.Diagnostics.Append(resp.State.SetAttribute(ctx, path.Root("instance_id"), parts[0])...)
	resp.Diagnostics.Append(resp.State.SetAttribute(ctx, path.Root("name"), parts[1])...)
	resp.Diagnostics.Append(resp.State.SetAttribute(ctx, path.Root("id"), parts[0]+"/"+parts[1])...)
}

// ModifyPlan replaces an object whose state says `error` (a failed create),
// even when it is not tainted — after an import or `terraform untaint`.
func (r *userResource) ModifyPlan(ctx context.Context, req resource.ModifyPlanRequest, resp *resource.ModifyPlanResponse) {
	messagingobj.ReplaceWhenErrored(ctx, req, resp)
}
